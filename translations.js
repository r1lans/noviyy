function getCurrentLang() {
    return localStorage.getItem('starthLang') || 'ru';
}

// Translate a key into the current language (falls back to Russian, then to the key itself)
function t(key) {
    const dict = TRANSLATIONS[getCurrentLang()] || TRANSLATIONS.ru;
    if (dict[key] !== undefined) return dict[key];
    return TRANSLATIONS.ru[key] !== undefined ? TRANSLATIONS.ru[key] : key;
}
window.t = t;

function applyTranslations(lang) {
    if (!TRANSLATIONS[lang]) lang = 'ru';
    const dict = TRANSLATIONS[lang];
    const get = (k) => (dict[k] !== undefined ? dict[k] : TRANSLATIONS.ru[k]);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const v = get(el.getAttribute('data-i18n'));
        if (v !== undefined) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const v = get(el.getAttribute('data-i18n-html'));
        if (v !== undefined) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const v = get(el.getAttribute('data-i18n-placeholder'));
        if (v !== undefined) el.setAttribute('placeholder', v);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const v = get(el.getAttribute('data-i18n-title'));
        if (v !== undefined) el.setAttribute('title', v);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const v = get(el.getAttribute('data-i18n-aria'));
        if (v !== undefined) el.setAttribute('aria-label', v);
    });

    const titleKey = document.documentElement.getAttribute('data-title-i18n');
    if (titleKey && get(titleKey)) document.title = get(titleKey);

    document.documentElement.lang = lang;
    localStorage.setItem('starthLang', lang);

    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    document.querySelectorAll(`.lang-btn[onclick*="'${lang}'"]`).forEach(btn => btn.classList.add('active'));

    // Let scripts that build text dynamically (pricing, nav button, ...) re-render
    window.dispatchEvent(new CustomEvent('starth-lang-changed', { detail: { lang } }));
}

function changeLanguage(langCode) {
    applyTranslations(langCode);
}

// Apply the saved language choice as soon as the page's DOM is ready
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getCurrentLang());
});
